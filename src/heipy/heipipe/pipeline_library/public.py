from ..step_library import (
    break_no,
    combining_to_entities,
    delete_comments,
    format_header,
    langusage,
    normalize_unicode,
)
from ..step_library.public import (
    check_for_ub_publisher,
    check_prefixes,
    replace_schema_url,
    update_changeList,
)
from ..steps import Pipeline


class PublicPipe(Pipeline):
    def __init__(self, parameters = None, *,
                 schema_url: str | None = None,
                 change_date: str | None = None,
                 change_message: str | None = None):
        """Public pipeline: prepares an edition file for publication.

        Steps: check_for_ub_publisher, delete_comments, normalize_unicode (NFC),
        check_prefixes, replace_schema_url, langusage, break_no, update_changeList,
        format_header, combining_to_entities.

        Args:
            parameters: Unused, kept for compatibility.
            schema_url: New URL for the xml-model processing instructions
                (step replace_schema_url).
            change_date: Date YYYY-MM-DD of the <change> added to the listChange
                (step update_changeList). Defaults to today's date.
            change_message: Text of that <change> (step update_changeList).
                Defaults to "This has been generated by heipy".
        """
        pipe_steps = [
            check_for_ub_publisher.get_step(),
            delete_comments.get_step(),
            normalize_unicode.get_step(),
            check_prefixes.get_step(),
            replace_schema_url.get_step(schema_url=schema_url),
            langusage.get_step(),
            break_no.get_step(),
            update_changeList.get_step(change_date=change_date, message=change_message),
            # string-based steps: Must not parse the document again after
            format_header.get_step(),
            combining_to_entities.get_step()
        ]
        
        description = "Public Pipeline - Standard"
        super().__init__(steps=pipe_steps, name="public_pipe", desc=description, serial=False)
