from ...steps import XsltStep


def get_step(change_date: str | None = None, message: str | None = None):
    """Adds a <change> to teiHeader/revisionDesc/listChange (creating them if missing).

    Args:
        change_date: Date of the change as YYYY-MM-DD (XSLT parameter ``changeDate``).
            Defaults to today's date.
        message: Text of the <change> (XSLT parameter ``message``).
            Defaults to "This has been generated by heipy".
    """
    step = XsltStep(
        files=["update_changeList.xsl"],
        name="update_changeList",
        pipe_files=True
    )
    if change_date is not None:
        step.set_parameter("changeDate", change_date)
    if message is not None:
        step.set_parameter("message", message)
    return step
